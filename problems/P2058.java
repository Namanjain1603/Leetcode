    public static int[] nodesBetweenCriticalPoints(ListNode head) {
        int i = 2;
        int a = -1, b = -1;
        int min = Integer.MAX_VALUE;
        ListNode prev = head;
        head = head.next;
        while (head.next != null) {
            ListNode curr = head;
            if ((curr.val > prev.val && curr.val > head.next.val)
                    || (curr.val < prev.val && curr.val < head.next.val)) {
                if (a == -1) {
                    a = i;
                } else {
                    min = Math.min(min, i - b);
                }
                b = i;
            }
            prev = head;
            head = head.next;
            i++;
        }
        if (a == b) {
            return new int[] { -1, -1 };
        }
        return new int[] { min, b - a };
    }

